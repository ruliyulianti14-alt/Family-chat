@Composable
fun FamilyAvatar(
    name: String,
    colorIndex: Long = 0L,
    size: Dp = 44.dp,
    modifier: Modifier = Modifier
) {
    val bgColor = FamilyAvatarColors[(colorIndex.toInt().coerceAtLeast(0)) % FamilyAvatarColors.size]
    val initials = name.trim()
        .split(" ")
        .filter { it.isNotBlank() }
        .take(2)
        .mapNotNull { it.firstOrNull()?.uppercaseChar() }
        .joinToString("")
        .ifBlank { "K" }

    Box(
        modifier = modifier
            .size(size)
            .clip(CircleShape)
            .background(bgColor),
        contentAlignment = Alignment.Center
    ) {
        Text(
            text = initials,
            color = Color.White,
            style = if (size >= 52.dp) MaterialTheme.typography.titleLarge else MaterialTheme.typography.titleMedium,
            fontWeight = FontWeight.Bold
        )
    }
}

